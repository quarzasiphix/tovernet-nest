/** Localised path: the audit page has different slugs per language. */
export function localPath(locale: Locale, path: string) {
  if (path === '/audyt-dostawcy-uslug-cyfrowych' && locale === 'en') return '/en/digital-provider-audit/';
  return `/${locale}${path}${path.endsWith('/') || path.includes('#') ? '' : '/'}`;
}
